ORG 100h

MOV AH, 01H
INT 21H

CMP AL, 65        
JB NOT_LETTER
CMP AL, 90        
JBE IS_UPPER

CMP AL, 97        
JB NOT_LETTER
CMP AL, 122       
JBE IS_LOWER

NOT_LETTER:
MOV DL, 'N'      
JMP DISPLAY

IS_UPPER:
MOV DL, 'U'       
JMP DISPLAY

IS_LOWER:
MOV DL, 'L'       

DISPLAY:
MOV AH, 02H
INT 21H

MOV AH, 4CH
INT 21H