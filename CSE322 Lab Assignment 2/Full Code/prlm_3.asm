.MODEL SMALL
.STACK 100H

.DATA

.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    MOV CX, 26
    MOV DL, 'A'
    MOV AH, 2

FORWARD_LOOP:
    INT 21H
    INC DL
    LOOP FORWARD_LOOP

    MOV DL, 0DH
    INT 21H
    MOV DL, 0AH
    INT 21H

    MOV CX, 26
    MOV DL, 'Z'

BACKWARD_LOOP:
    INT 21H
    DEC DL
    LOOP BACKWARD_LOOP

    MOV AH, 4CH
    INT 21H
MAIN ENDP
END MAIN